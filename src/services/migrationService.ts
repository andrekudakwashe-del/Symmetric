/**
 * Split staged rows into manageable batches for staff delegation
 */
export function partitionRowsIntoBatches(
  totalRows: number,
  batchSize: number = 250,
  staffList?: Salesperson[]
): BatchPartition[] {
  const partitions: BatchPartition[] = [];
  const numBatches = Math.ceil(totalRows / batchSize);

  for (let b = 0; b < numBatches; b++) {
    const startIndex = b * batchSize;
    const endIndex = Math.min((b + 1) * batchSize - 1, totalRows - 1);
    const count = endIndex - startIndex + 1;

    // Optional round-robin assignment to active staff
    let assignedStaff: Salesperson | undefined;
    if (staffList && staffList.length > 0) {
      assignedStaff = staffList[b % staffList.length];
    }

    partitions.push({
      id: `batch_${b + 1}_${Date.now()}`,
      batchNumber: b + 1,
      title: `Batch ${b + 1} (Rows ${startIndex + 1} - ${endIndex + 1})`,
      startIndex,
      endIndex,
      totalRows: count,
      status: 'pending',
      assignedStaffId: assignedStaff?.id,
      assignedStaffName: assignedStaff?.name,
    });
  }

  return partitions;
}

