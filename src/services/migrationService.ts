/**
 * Automatically map raw spreadsheet headers to Saimetric fields using fuzzy synonym dictionary
 */
export function autoMatchHeaders(
  entityType: MigrationEntityType,
  rawHeaders: string[]
): Record<string, ColumnMapping> {
  const fields = getFieldDefinitionsForEntity(entityType);
  const mappings: Record<string, ColumnMapping> = {};
  const usedRawHeaders = new Set<string>();
  const matchedFieldMap: Record<string, string> = {};

  const systemMap =
    entityType === 'inventory'
      ? SYSTEM_INVENTORY_HEADER_MAP
      : entityType === 'customers'
      ? SYSTEM_CUSTOMER_HEADER_MAP
      : SYSTEM_SUPPLIER_HEADER_MAP;

  // Pass 1: Saimetric System Known Exact Header Matching (100% guarantee for system exported files)
  for (const raw of rawHeaders) {
    const cleanRaw = normalizeHeaderString(raw);
    const targetKey = systemMap[cleanRaw];
    if (targetKey && !matchedFieldMap[targetKey] && fields.some((f) => f.key === targetKey)) {
      matchedFieldMap[targetKey] = raw;
      usedRawHeaders.add(raw);
    }
  }

  // Pass 2: Exact Match on field.key, field.label, or exact synonym
  for (const field of fields) {
    if (matchedFieldMap[field.key]) continue;
    const normKey = normalizeHeaderString(field.key);
    const normLabel = normalizeHeaderString(field.label);
    const normSynonyms = field.synonyms.map(normalizeHeaderString);

    for (const raw of rawHeaders) {
      if (usedRawHeaders.has(raw)) continue;
      const cleanRaw = normalizeHeaderString(raw);

      if (cleanRaw === normKey || cleanRaw === normLabel || normSynonyms.includes(cleanRaw)) {
        matchedFieldMap[field.key] = raw;
        usedRawHeaders.add(raw);
        break;
      }
    }
  }

  // Pass 3: Bounded partial matching (only for longer words, strictly avoiding generic collisions like 'item')
  for (const field of fields) {
    if (matchedFieldMap[field.key]) continue;
    const normSynonyms = field.synonyms.map(normalizeHeaderString).filter((s) => s.length >= 4);

    for (const raw of rawHeaders) {
      if (usedRawHeaders.has(raw)) continue;
      const cleanRaw = normalizeHeaderString(raw);

      const partialMatch = normSynonyms.find((s) => {
        if (cleanRaw.includes(s) || (s.includes(cleanRaw) && cleanRaw.length >= 4)) {
          return true;
        }
        return false;
      });

      if (partialMatch) {
        matchedFieldMap[field.key] = raw;
        usedRawHeaders.add(raw);
        break;
      }
    }
  }

  // Build final mappings
  for (const field of fields) {
    mappings[field.key] = {
      targetFieldKey: field.key,
      sourceHeader: matchedFieldMap[field.key] || null,
      isAutoGenerated: false,
    };
  }

  return mappings;
}

