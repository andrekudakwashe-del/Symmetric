function toTitleCase(str: string): string {
  if (!str) return '';
  return str.replace(/\w\S*/g, (txt) => txt.charAt(0).toUpperCase() + txt.substring(1).toLowerCase());
}

/**
 * Apply column mappings, formula calculations, auto-SKUs, and data cleansing to raw rows
 */
export function applyMappingAndFormulas(
  entityType: MigrationEntityType,
  rawRows: Record<string, any>[],
  mappings: Record<string, ColumnMapping>,
  formulas: FormulaConfig
): StagedRow[] {
  const fields = getFieldDefinitionsForEntity(entityType);
  const stagedRows: StagedRow[] = [];

  const existingInventory = entityType === 'inventory' ? getInventoryItems() : [];
  const existingCustomers = entityType === 'customers' ? getCustomers() : [];
  const existingSuppliers = entityType === 'suppliers' ? getSuppliers() : [];

  const existingBarcodes = new Set(existingInventory.map((i) => i.barcode).filter(Boolean));
  const existingSkus = new Set(existingInventory.map((i) => i.sku).filter(Boolean));
  const existingNames = new Set<string>();
  if (entityType === 'inventory') {
    existingInventory.forEach((it) => {
      if (it.itemName) existingNames.add(it.itemName.toLowerCase().trim());
    });
  } else if (entityType === 'customers') {
    existingCustomers.forEach((c) => {
      if (c.name) existingNames.add(c.name.toLowerCase().trim());
    });
  } else if (entityType === 'suppliers') {
    existingSuppliers.forEach((s) => {
      if (s.name) existingNames.add(s.name.toLowerCase().trim());
    });
  }

  for (let idx = 0; idx < rawRows.length; idx++) {
    const raw = rawRows[idx];
    const rowId = `stg_row_${Date.now()}_${idx}`;
    const rowData: Record<string, any> = { _rowId: rowId };
    const validationErrors: string[] = [];

    // 1. Map raw fields
    for (const field of fields) {
      const mapping = mappings[field.key];
      const sourceHeader = mapping?.sourceHeader;

      let val: any = sourceHeader ? raw[sourceHeader] : undefined;

      if (val === undefined || val === null || val === '') {
        val = field.defaultValue !== undefined ? field.defaultValue : '';
      }

      // Convert data types
      if (field.type === 'number') {
        const num = parseFloat(String(val).replace(/[^0-9.-]/g, ''));
        val = isNaN(num) ? field.defaultValue || 0 : num;
      } else if (field.type === 'string') {
        val = String(val).trim();
        if (formulas.cleanText) {
          if (field.key === 'name' || field.key === 'category') {
            val = toTitleCase(val);
          }
        }
      }

      rowData[field.key] = val;
    }

    // 2. Auto-Generate SKU / Item Code if missing or requested
    if (entityType === 'inventory') {
      const hasSku = Boolean(rowData.sku && String(rowData.sku).trim().length > 0);
      const hasItemId = Boolean(rowData.itemId && String(rowData.itemId).trim().length > 0);

      if (!hasItemId) {
        rowData.itemId = hasSku ? String(rowData.sku).trim() : `PRD_${Date.now()}_${idx}`;
      }

      if (!hasSku) {
        if (hasItemId) {
          rowData.sku = String(rowData.itemId).trim();
        } else if (formulas.autoGenerateSku) {
          const prefix = formulas.skuPrefix || 'PRD';
          const numStr = String(idx + 1).padStart(formulas.skuDigits || 4, '0');
          rowData.sku = `${prefix}-${numStr}`;
        }
      }

      // 3. Formula Engine: Case & Packaging conversion
      let cost = rowData.costPrice || 0;
      let caseQty = rowData.caseQuantity || formulas.defaultCaseQuantity || 1;
      let caseCost = rowData.caseCost || 0;

      if (formulas.caseFormula === 'case_cost_from_unit') {
        // Case Cost = Unit Cost * Case Quantity
        caseCost = Math.round(cost * caseQty * 100) / 100;
        rowData.caseCost = caseCost;
        rowData.caseQuantity = caseQty;
      } else if (formulas.caseFormula === 'unit_cost_from_case' && caseQty > 0 && caseCost > 0) {
        // Unit Cost = Case Cost / Case Quantity
        cost = Math.round((caseCost / caseQty) * 100) / 100;
        rowData.costPrice = cost;
      } else if (caseCost === 0 && cost > 0 && caseQty > 1) {
        // Default sane fallback
        rowData.caseCost = Math.round(cost * caseQty * 100) / 100;
      }

      // Stock quantity reconciliation
      const cases = Number(rowData.stockCases) || 0;
      const singles = Number(rowData.stockSingles) || 0;
      let totalUnits = Number(rowData.stockQuantity) || 0;
      if (totalUnits === 0 && (cases > 0 || singles > 0)) {
        totalUnits = cases * caseQty + singles;
        rowData.stockQuantity = totalUnits;
      } else if (totalUnits > 0 && cases === 0 && singles === 0 && caseQty > 1) {
        rowData.stockCases = Math.floor(totalUnits / caseQty);
        rowData.stockSingles = totalUnits % caseQty;
      }

      // 4. Formula Engine: Markup Pricing
      if (formulas.markupFormula === 'cost_plus_markup' && formulas.markupPercent > 0) {
        const markupMul = 1 + formulas.markupPercent / 100;
        rowData.sellingPrice = Math.round(cost * markupMul * 100) / 100;
      }

      // 5. Tax Adjustment Formula (Add VAT)
      if (formulas.taxAdjustment === 'add_vat' && formulas.taxPercent > 0) {
        const vatMul = 1 + formulas.taxPercent / 100;
        rowData.sellingPrice = Math.round(rowData.sellingPrice * vatMul * 100) / 100;
      }

      // 6. Packaging Variants (Prepacks) Processing & Parsing
      let parsedVariants: PackagingVariant[] = [];
      if (formulas.variantImportMode === 'auto_generate') {
        const currentCost = rowData.costPrice || 0;
        const currentSell = rowData.sellingPrice || 0;
        const disc = (formulas.autoVariantDiscountPercent || 5) / 100;
        if (formulas.autoVariantPreset === 'five_pack') {
          parsedVariants.push({
            id: `VAR-5PK-${idx + 1}`,
            name: 'Prepack (5s)',
            unitsPerPack: 5,
            sellPrice: Math.round(currentSell * 5 * (1 - disc) * 100) / 100,
            costPrice: Math.round(currentCost * 5 * 100) / 100,
          });
        } else if (formulas.autoVariantPreset === 'ten_pack') {
          parsedVariants.push({
            id: `VAR-10PK-${idx + 1}`,
            name: 'Pack of 10s',
            unitsPerPack: 10,
            sellPrice: Math.round(currentSell * 10 * (1 - disc) * 100) / 100,
            costPrice: Math.round(currentCost * 10 * 100) / 100,
          });
        } else if (formulas.autoVariantPreset === 'double_pack') {
          parsedVariants.push({
            id: `VAR-2PK-${idx + 1}`,
            name: 'Double Pack (2s)',
            unitsPerPack: 2,
            sellPrice: Math.round(currentSell * 2 * (1 - disc) * 100) / 100,
            costPrice: Math.round(currentCost * 2 * 100) / 100,
          });
        } else if (formulas.autoVariantPreset === 'half_pack') {
          parsedVariants.push({
            id: `VAR-HALF-${idx + 1}`,
            name: 'Half Portion (0.5)',
            unitsPerPack: 0.5,
            sellPrice: Math.round(currentSell * 0.5 * 100) / 100,
            costPrice: Math.round(currentCost * 0.5 * 100) / 100,
          });
        }
      } else if (formulas.variantImportMode !== 'none' && rowData.packagingVariants) {
        parsedVariants = parsePackagingVariantsString(rowData.packagingVariants);
      }
      rowData._parsedVariants = parsedVariants;
      if (parsedVariants.length > 0 && !rowData.packagingVariants) {
        rowData.packagingVariants = serializePackagingVariants(parsedVariants);
      }
    } else if (entityType === 'customers') {
      // Auto-generate Customer code if wanted
      if (!rowData.id) {
        const prefix = formulas.skuPrefix || 'CUST';
        const numStr = String(idx + 1).padStart(formulas.skuDigits || 4, '0');
        rowData.customerCode = `${prefix}-${numStr}`;
      }
    } else if (entityType === 'suppliers') {
      if (!rowData.id) {
        const prefix = formulas.skuPrefix || 'SUP';
        const numStr = String(idx + 1).padStart(formulas.skuDigits || 4, '0');
        rowData.supplierCode = `${prefix}-${numStr}`;
      }
    }

    // 6. Validation Checks
    for (const field of fields) {
      if (field.required) {
        const val = rowData[field.key];
        if (val === undefined || val === null || val === '') {
          validationErrors.push(`Required field '${field.label}' is missing.`);
        }
      }
    }

    // Duplicate detection
    let isDuplicate = false;
    if (entityType === 'inventory') {
      if (rowData.barcode && existingBarcodes.has(rowData.barcode)) {
        isDuplicate = true;
      } else if (rowData.sku && existingSkus.has(rowData.sku)) {
        isDuplicate = true;
      } else if (rowData.name && existingNames.has(rowData.name.toLowerCase().trim())) {
        isDuplicate = true;
      }
    } else if (rowData.name && existingNames.has(rowData.name.toLowerCase().trim())) {
      isDuplicate = true;
    }

    rowData._isValid = validationErrors.length === 0;
    rowData._validationErrors = validationErrors;
    rowData._isDuplicate = isDuplicate;

    stagedRows.push(rowData as StagedRow);
  }

  return stagedRows;
}

