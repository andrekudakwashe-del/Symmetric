/**
 * Commit validated staged rows to the live store with automated safety snapshot
 */
export function commitMigrationJob(
  job: MigrationJob,
  conflictPolicy: DuplicateConflictPolicy = 'update'
): MigrationCommitResult {
  if (typeof window === 'undefined' || !window.localStorage) {
    return { success: false, recordsAdded: 0, recordsUpdated: 0, recordsSkipped: 0, message: 'LocalStorage unavailable' };
  }

  const snapshotKey = `saimetric_pre_migration_backup_${job.id}`;

  try {
    // 1. Take safety snapshot of target table safely
    try {
      if (job.entityType === 'inventory') {
        const current = window.localStorage.getItem('saimetric_room_inventory_items') || '[]';
        window.sessionStorage.setItem(snapshotKey, current);
        window.localStorage.setItem(snapshotKey, current);
      } else if (job.entityType === 'customers') {
        const current = window.localStorage.getItem('saimetric_room_customers') || '[]';
        window.localStorage.setItem(snapshotKey, current);
      } else if (job.entityType === 'suppliers') {
        const current = window.localStorage.getItem('saimetric_room_suppliers') || '[]';
        window.localStorage.setItem(snapshotKey, current);
      }
    } catch (snapErr) {
      console.warn('[MigrationService] Snapshot storage warning (quota limited):', snapErr);
    }

    let recordsAdded = 0;
    let recordsUpdated = 0;
    let recordsSkipped = 0;

    // 2. Commit based on entity type
    const compId = getCurrentCompanyId() || 'COMP-001';
    const brId = getCurrentBranchId() || 'BR-MAIN';

    if (job.entityType === 'inventory') {
      const currentItems = getInventoryItems();
      const itemMap = new Map<string, InventoryItem>();
      currentItems.forEach((it) => {
        if (it.itemId) itemMap.set(`id_${it.itemId.toUpperCase().trim()}`, it);
        if (it.barcode) itemMap.set(`barcode_${it.barcode}`, it);
        if (it.sku) itemMap.set(`sku_${it.sku.toUpperCase().trim()}`, it);
        if (it.itemName) itemMap.set(`name_${it.itemName.toLowerCase().trim()}`, it);
      });

      for (let idx = 0; idx < job.stagedRows.length; idx++) {
        const row = job.stagedRows[idx];
        if (!row._isValid) continue;

        let existing: InventoryItem | undefined;
        if (row.itemId) existing = itemMap.get(`id_${String(row.itemId).toUpperCase().trim()}`);
        if (!existing && row.barcode) existing = itemMap.get(`barcode_${row.barcode}`);
        if (!existing && row.sku) existing = itemMap.get(`sku_${String(row.sku).toUpperCase().trim()}`);
        if (!existing && row.name) existing = itemMap.get(`name_${String(row.name).toLowerCase().trim()}`);

        const costPerUnit = Number(row.costPrice) || 0;
        const sellPriceUnit = Number(row.sellingPrice) || 0;
        const unitsPerCase = Number(row.caseQuantity) || 1;
        const costPerCase = Number(row.caseCost) || (costPerUnit * unitsPerCase);
        const sellPriceCase = sellPriceUnit * unitsPerCase;
        const totalUnits = Number(row.stockQuantity) || 0;
        const stockCases = Number(row.stockCases) || (unitsPerCase > 1 ? Math.floor(totalUnits / unitsPerCase) : 0);
        const stockSingles = Number(row.stockSingles) || (unitsPerCase > 1 ? totalUnits % unitsPerCase : totalUnits);

        const parsedVariants: PackagingVariant[] =
          Array.isArray(row._parsedVariants) && row._parsedVariants.length > 0
            ? row._parsedVariants
            : (Array.isArray(row.packagingVariants)
                ? row.packagingVariants
                : parsePackagingVariantsString(row.packagingVariants));

        // Check if this row is a prepack/variant that links to a parent product
        const parentKey = row.parentId ? String(row.parentId).trim() : null;
        if (parentKey) {
          const parentItem =
            itemMap.get(`id_${parentKey.toUpperCase()}`) ||
            itemMap.get(`sku_${parentKey.toUpperCase()}`) ||
            itemMap.get(`name_${parentKey.toLowerCase()}`);

          if (parentItem) {
            const varUnits = Number(row.variantUnits) || Number(row.caseQuantity) || 1;
            const varSell = Number(row.sellingPrice) || Number((parentItem.sellPriceUnit * varUnits).toFixed(2));
            const varCost = Number(row.costPrice) || Number((parentItem.costPerUnit * varUnits).toFixed(2));

            const curVariants: PackagingVariant[] = Array.isArray(parentItem.packagingVariants)
              ? [...parentItem.packagingVariants]
              : [];

            const existingIdx = curVariants.findIndex(
              (v) => (row.sku && v.sku === row.sku) || v.name.toLowerCase() === String(row.name).toLowerCase()
            );

            const packVar: PackagingVariant = {
              id:
                existingIdx >= 0
                  ? curVariants[existingIdx].id
                  : `VAR-${Date.now().toString().slice(-4)}-${curVariants.length + 1}`,
              name: row.name,
              unitsPerPack: varUnits,
              sellPrice: varSell,
              costPrice: varCost > 0 ? varCost : undefined,
              barcode: row.barcode || undefined,
              sku: row.sku || undefined,
            };

            if (existingIdx >= 0) {
              curVariants[existingIdx] = packVar;
            } else {
              curVariants.push(packVar);
            }

            parentItem.packagingVariants = curVariants;

            // Convert variant stock to parent units (Question 3: convert to parent units)
            const addedUnits = totalUnits > 0 ? totalUnits * varUnits : 0;
            if (addedUnits > 0) {
              parentItem.totalUnits = (parentItem.totalUnits || 0) + addedUnits;
              if (parentItem.unitsPerCase > 1) {
                parentItem.stockCases = Math.floor(parentItem.totalUnits / parentItem.unitsPerCase);
                parentItem.stockSingles = parentItem.totalUnits % parentItem.unitsPerCase;
              } else {
                parentItem.stockCases = 0;
                parentItem.stockSingles = parentItem.totalUnits;
              }
            }

            parentItem.lastUpdated = new Date().toISOString();
            saveInventoryItem(parentItem);
            if (parentItem.itemId) itemMap.set(`id_${parentItem.itemId.toUpperCase().trim()}`, parentItem);
            if (parentItem.sku) itemMap.set(`sku_${parentItem.sku.toUpperCase().trim()}`, parentItem);
            recordsUpdated++;
            continue;
          }
        }

        if (existing) {
          if (conflictPolicy === 'skip') {
            recordsSkipped++;
            continue;
          } else if (conflictPolicy === 'update') {
            const updatedItem: InventoryItem = {
              ...existing,
              itemId: row.itemId || existing.itemId,
              itemName: row.name || existing.itemName,
              costPerUnit,
              sellPriceUnit,
              unitsPerCase,
              costPerCase,
              sellPriceCase,
              totalUnits: (existing.totalUnits || 0) + totalUnits,
              stockCases: (existing.stockCases || 0) + stockCases,
              stockSingles: (existing.stockSingles || 0) + stockSingles,
              category: row.category || existing.category || 'General',
              sku: row.sku || existing.sku,
              barcode: row.barcode || existing.barcode,
              canSellAsCase: row.canSellAsCase !== undefined
                ? ['y', 'yes', 'true', '1'].includes(String(row.canSellAsCase).toLowerCase())
                : existing.canSellAsCase,
              packagingVariants: parsedVariants.length > 0 ? parsedVariants : existing.packagingVariants,
              description: row.description || existing.description,
              reorderLevelCases: Number(row.reorderLevelCases) || existing.reorderLevelCases || 2,
              reorderLevelUnits: Number(row.minStock) || existing.reorderLevelUnits || 5,
              company_id: compId,
              companyId: compId,
              branch_id: brId,
              branchId: brId,
              lastUpdated: new Date().toISOString(),
            };
            saveInventoryItem(updatedItem);
            recordsUpdated++;
            continue;
          }
        }

        // New item
        const itemId = (row.itemId && String(row.itemId).trim()) || `PRD_${Date.now()}_${idx}_${Math.random().toString(36).substring(2, 6)}`;
        const newItem: InventoryItem = {
          itemId,
          itemName: row.name,
          category: row.category || 'General',
          sku: row.sku || itemId,
          barcode: row.barcode || '',
          unitsPerCase,
          costPerCase,
          costPerUnit,
          sellPriceCase,
          sellPriceUnit,
          stockCases,
          stockSingles,
          totalUnits,
          canSellAsCase: ['y', 'yes', 'true', '1'].includes(String(row.canSellAsCase || '').toLowerCase()),
          packagingVariants: parsedVariants.length > 0 ? parsedVariants : undefined,
          description: row.description || '',
          reorderLevelCases: Number(row.reorderLevelCases) || 2,
          reorderLevelUnits: Number(row.minStock) || Math.max(5, unitsPerCase),
          company_id: compId,
          companyId: compId,
          branch_id: brId,
          branchId: brId,
          lastUpdated: new Date().toISOString(),
        };

        saveInventoryItem(newItem);
        if (newItem.itemId) itemMap.set(`id_${newItem.itemId.toUpperCase().trim()}`, newItem);
        if (newItem.sku) itemMap.set(`sku_${newItem.sku.toUpperCase().trim()}`, newItem);
        if (newItem.itemName) itemMap.set(`name_${newItem.itemName.toLowerCase().trim()}`, newItem);
        recordsAdded++;
      }
    } else if (job.entityType === 'customers') {
      const customersToImport: Customer[] = job.stagedRows
        .filter((r) => r._isValid)
        .map((row, idx) => ({
          customerId: row.customerCode || row.customerId || `CUST_${Date.now()}_${idx}`,
          name: row.name,
          phone: row.phone || '',
          address: row.address || '',
          creditLimit: Number(row.creditLimit) || 0,
          currentBalance: Number(row.currentBalance) || 0,
          company_id: compId,
          companyId: compId,
          createdBy: 'Migration_Wizard',
          createdDate: new Date().toISOString().split('T')[0],
        }));

      const res = importCustomersList(customersToImport, conflictPolicy === 'skip' ? 'merge' : 'merge');
      recordsAdded = res.added;
      recordsUpdated = res.updated;
    } else if (job.entityType === 'suppliers') {
      const suppliersToImport: Supplier[] = job.stagedRows
        .filter((r) => r._isValid)
        .map((row, idx) => ({
          supplierId: row.supplierCode || row.supplierId || `SUP_${Date.now()}_${idx}`,
          name: row.name,
          category: row.category || 'General',
          contactPerson: row.contactPerson || '',
          phone: row.phone || '',
          email: row.email || '',
          paymentTerms: row.paymentTerms || 'COD',
          address: row.address || '',
          status: 'Active' as const,
          company_id: compId,
          companyId: compId,
          createdDate: new Date().toISOString().split('T')[0],
        }));

      const res = importSuppliersList(suppliersToImport, conflictPolicy === 'skip' ? 'merge' : 'merge');
      recordsAdded = res.added;
      recordsUpdated = res.updated;
    }

    // 3. Mark job as committed
    job.status = 'committed';
    job.committedAt = new Date().toISOString();
    job.rollbackSnapshotKey = snapshotKey;
    saveMigrationJob(job);

    // Notify application listeners
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('saimetric_inventory_updated', { detail: { count: recordsAdded } }));
      window.dispatchEvent(new CustomEvent('saimetric_customers_updated', { detail: { count: recordsAdded } }));
      window.dispatchEvent(new CustomEvent('saimetric_suppliers_updated', { detail: { count: recordsAdded } }));
    }

    return {
      success: true,
      recordsAdded,
      recordsUpdated,
      recordsSkipped,
      rollbackKey: snapshotKey,
      message: `Successfully migrated ${recordsAdded + recordsUpdated} records (${recordsAdded} new, ${recordsUpdated} updated, ${recordsSkipped} skipped).`,
    };
  } catch (err: any) {
    return {
      success: false,
      recordsAdded: 0,
      recordsUpdated: 0,
      recordsSkipped: 0,
      message: `Migration commit failed: ${err.message}`,
    };
  }
}

/**
 * Asynchronous chunked commit with live progress reporting for large files
 */
export async function commitMigrationJobAsync(
  job: MigrationJob,
  conflictPolicy: DuplicateConflictPolicy = 'update',
  onProgress?: MigrationProgressCallback
): Promise<MigrationCommitResult> {
  if (typeof window === 'undefined' || !window.localStorage) {
    return { success: false, recordsAdded: 0, recordsUpdated: 0, recordsSkipped: 0, message: 'LocalStorage unavailable' };
  }

  const snapshotKey = `saimetric_pre_migration_backup_${job.id}`;

  try {
    try {
      if (job.entityType === 'inventory') {
        const current = window.localStorage.getItem('saimetric_room_inventory_items') || '[]';
        window.sessionStorage.setItem(snapshotKey, current);
        window.localStorage.setItem(snapshotKey, current);
      } else if (job.entityType === 'customers') {
        const current = window.localStorage.getItem('saimetric_room_customers') || '[]';
        window.localStorage.setItem(snapshotKey, current);
      } else if (job.entityType === 'suppliers') {
        const current = window.localStorage.getItem('saimetric_room_suppliers') || '[]';
        window.localStorage.setItem(snapshotKey, current);
      }
    } catch (snapErr) {
      console.warn('[MigrationService] Snapshot storage warning (quota limited):', snapErr);
    }

    let recordsAdded = 0;
    let recordsUpdated = 0;
    let recordsSkipped = 0;

    const compId = getCurrentCompanyId() || 'COMP-001';
    const brId = getCurrentBranchId() || 'BR-MAIN';

    if (job.entityType === 'inventory') {
      const currentItems = getInventoryItems();
      const itemMap = new Map<string, InventoryItem>();
      currentItems.forEach((it) => {
        if (it.itemId) itemMap.set(`id_${it.itemId.toUpperCase().trim()}`, it);
        if (it.barcode) itemMap.set(`barcode_${it.barcode}`, it);
        if (it.sku) itemMap.set(`sku_${it.sku.toUpperCase().trim()}`, it);
        if (it.itemName) itemMap.set(`name_${it.itemName.toLowerCase().trim()}`, it);
      });

      const totalRows = job.stagedRows.length;

      for (let idx = 0; idx < totalRows; idx++) {
        const row = job.stagedRows[idx];

        if (onProgress) {
          const percent = Math.min(99, Math.round(((idx + 1) / totalRows) * 100));
          onProgress(idx + 1, totalRows, percent, row.name || row.itemId);
          if (idx % 12 === 0) {
            await new Promise((r) => setTimeout(r, 0));
          }
        }

        if (!row._isValid) continue;

        let existing: InventoryItem | undefined;
        if (row.itemId) existing = itemMap.get(`id_${String(row.itemId).toUpperCase().trim()}`);
        if (!existing && row.barcode) existing = itemMap.get(`barcode_${row.barcode}`);
        if (!existing && row.sku) existing = itemMap.get(`sku_${String(row.sku).toUpperCase().trim()}`);
        if (!existing && row.name) existing = itemMap.get(`name_${String(row.name).toLowerCase().trim()}`);

        const costPerUnit = Number(row.costPrice) || 0;
        const sellPriceUnit = Number(row.sellingPrice) || 0;
        const unitsPerCase = Number(row.caseQuantity) || 1;
        const costPerCase = Number(row.caseCost) || (costPerUnit * unitsPerCase);
        const sellPriceCase = sellPriceUnit * unitsPerCase;
        const totalUnits = Number(row.stockQuantity) || 0;
        const stockCases = Number(row.stockCases) || (unitsPerCase > 1 ? Math.floor(totalUnits / unitsPerCase) : 0);
        const stockSingles = Number(row.stockSingles) || (unitsPerCase > 1 ? totalUnits % unitsPerCase : totalUnits);

        const parsedVariants: PackagingVariant[] =
          Array.isArray(row._parsedVariants) && row._parsedVariants.length > 0
            ? row._parsedVariants
            : (Array.isArray(row.packagingVariants)
                ? row.packagingVariants
                : parsePackagingVariantsString(row.packagingVariants));

        const parentKey = row.parentId ? String(row.parentId).trim() : null;
        if (parentKey) {
          const parentItem =
            itemMap.get(`id_${parentKey.toUpperCase()}`) ||
            itemMap.get(`sku_${parentKey.toUpperCase()}`) ||
            itemMap.get(`name_${parentKey.toLowerCase()}`);

          if (parentItem) {
            const varUnits = Number(row.variantUnits) || Number(row.caseQuantity) || 1;
            const varSell = Number(row.sellingPrice) || Number((parentItem.sellPriceUnit * varUnits).toFixed(2));
            const varCost = Number(row.costPrice) || Number((parentItem.costPerUnit * varUnits).toFixed(2));

            const curVariants: PackagingVariant[] = Array.isArray(parentItem.packagingVariants)
              ? [...parentItem.packagingVariants]
              : [];

            const existingIdx = curVariants.findIndex(
              (v) => (row.sku && v.sku === row.sku) || v.name.toLowerCase() === String(row.name).toLowerCase()
            );

            const packVar: PackagingVariant = {
              id:
                existingIdx >= 0
                  ? curVariants[existingIdx].id
                  : `VAR-${Date.now().toString().slice(-4)}-${curVariants.length + 1}`,
              name: row.name,
              unitsPerPack: varUnits,
              sellPrice: varSell,
              costPrice: varCost > 0 ? varCost : undefined,
              barcode: row.barcode || undefined,
              sku: row.sku || undefined,
            };

            if (existingIdx >= 0) {
              curVariants[existingIdx] = packVar;
            } else {
              curVariants.push(packVar);
            }

            parentItem.packagingVariants = curVariants;

            const addedUnits = totalUnits > 0 ? totalUnits * varUnits : 0;
            if (addedUnits > 0) {
              parentItem.totalUnits = (parentItem.totalUnits || 0) + addedUnits;
              if (parentItem.unitsPerCase > 1) {
                parentItem.stockCases = Math.floor(parentItem.totalUnits / parentItem.unitsPerCase);
                parentItem.stockSingles = parentItem.totalUnits % parentItem.unitsPerCase;
              } else {
                parentItem.stockCases = 0;
                parentItem.stockSingles = parentItem.totalUnits;
              }
            }

            parentItem.lastUpdated = new Date().toISOString();
            saveInventoryItem(parentItem);
            if (parentItem.itemId) itemMap.set(`id_${parentItem.itemId.toUpperCase().trim()}`, parentItem);
            if (parentItem.sku) itemMap.set(`sku_${parentItem.sku.toUpperCase().trim()}`, parentItem);
            recordsUpdated++;
            continue;
          }
        }

        if (existing) {
          if (conflictPolicy === 'skip') {
            recordsSkipped++;
            continue;
          }
          const updatedItem: InventoryItem = {
            ...existing,
            itemName: row.name || existing.itemName,
            category: row.category || existing.category,
            costPrice: costPerUnit || existing.costPrice,
            costPerUnit: costPerUnit || existing.costPerUnit,
            costPerCase: costPerCase || existing.costPerCase,
            sellingPrice: sellPriceUnit || existing.sellingPrice,
            sellPriceUnit: sellPriceUnit || existing.sellPriceUnit,
            sellPriceCase: sellPriceCase || existing.sellPriceCase,
            unitsPerCase: unitsPerCase || existing.unitsPerCase,
            stockCases: stockCases !== undefined ? stockCases : existing.stockCases,
            stockSingles: stockSingles !== undefined ? stockSingles : existing.stockSingles,
            totalUnits: totalUnits !== undefined ? totalUnits : existing.totalUnits,
            barcode: row.barcode || existing.barcode,
            sku: row.sku || existing.sku,
            packagingVariants: parsedVariants.length > 0 ? parsedVariants : existing.packagingVariants,
            lastUpdated: new Date().toISOString(),
          };
          saveInventoryItem(updatedItem);
          itemMap.set(`id_${updatedItem.itemId.toUpperCase().trim()}`, updatedItem);
          recordsUpdated++;
        } else {
          const newItemId = row.itemId
            ? String(row.itemId).trim().toUpperCase()
            : (row.sku ? String(row.sku).trim().toUpperCase() : `ITM-${Date.now().toString().slice(-5)}-${idx}`);

          const newItem: InventoryItem = {
            itemId: newItemId,
            itemName: row.name || 'Migrated Item',
            category: row.category || 'General',
            costPrice: costPerUnit,
            costPerUnit,
            costPerCase,
            sellingPrice: sellPriceUnit,
            sellPriceUnit,
            sellPriceCase,
            unitsPerCase,
            stockCases,
            stockSingles,
            totalUnits,
            reorderLevelCases: 2,
            reorderLevelUnits: 10,
            barcode: row.barcode || '',
            sku: row.sku || newItemId,
            canSellAsCase: unitsPerCase > 1,
            packagingVariants: parsedVariants,
            company_id: compId,
            branch_id: brId,
            lastUpdated: new Date().toISOString(),
          };
          saveInventoryItem(newItem);
          itemMap.set(`id_${newItem.itemId.toUpperCase().trim()}`, newItem);
          recordsAdded++;
        }
      }
    } else if (job.entityType === 'customers') {
      const customersToImport: Partial<Customer>[] = job.stagedRows
        .filter((r) => r._isValid)
        .map((r, idx) => ({
          customerId: r.customerId || `CUST-MIG-${Date.now().toString().slice(-4)}-${idx}`,
          name: r.name,
          phone: r.phone || '',
          email: r.email || '',
          companyName: r.companyName || '',
          nationalId: r.nationalId || '',
          creditLimit: Number(r.creditLimit) || 0,
          currentBalance: Number(r.openingBalance) || 0,
          status: 'Active',
          createdDate: new Date().toISOString().split('T')[0],
        }));

      const res = importCustomersList(customersToImport, conflictPolicy === 'skip' ? 'merge' : 'merge');
      recordsAdded = res.added;
      recordsUpdated = res.updated;
    } else if (job.entityType === 'suppliers') {
      const suppliersToImport: Partial<Supplier>[] = job.stagedRows
        .filter((r) => r._isValid)
        .map((r, idx) => ({
          supplierId: r.supplierId || `SUP-MIG-${Date.now().toString().slice(-4)}-${idx}`,
          name: r.name,
          contactPerson: r.contactPerson || '',
          phone: r.phone || '',
          email: r.email || '',
          address: r.address || '',
          currency: r.currency || 'USD',
          status: 'Active',
          createdDate: new Date().toISOString().split('T')[0],
        }));

      const res = importSuppliersList(suppliersToImport, conflictPolicy === 'skip' ? 'merge' : 'merge');
      recordsAdded = res.added;
      recordsUpdated = res.updated;
    }

    if (onProgress) {
      onProgress(job.stagedRows.length, job.stagedRows.length, 100, 'Complete');
    }

    job.status = 'committed';
    job.committedAt = new Date().toISOString();
    job.rollbackSnapshotKey = snapshotKey;
    saveMigrationJob(job);

    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('saimetric_inventory_updated', { detail: { count: recordsAdded } }));
      window.dispatchEvent(new CustomEvent('saimetric_customers_updated', { detail: { count: recordsAdded } }));
      window.dispatchEvent(new CustomEvent('saimetric_suppliers_updated', { detail: { count: recordsAdded } }));
    }

    return {
      success: true,
      recordsAdded,
      recordsUpdated,
      recordsSkipped,
      rollbackKey: snapshotKey,
      message: `Successfully migrated ${recordsAdded + recordsUpdated} records (${recordsAdded} new, ${recordsUpdated} updated, ${recordsSkipped} skipped).`,
    };
  } catch (err: any) {
    return {
      success: false,
      recordsAdded: 0,
      recordsUpdated: 0,
      recordsSkipped: 0,
      message: `Migration commit failed: ${err.message}`,
    };
  }
}

/**
 * One-click safety rollback to the exact pre-migration snapshot
 */
export function rollbackMigrationJob(job: MigrationJob): { success: boolean; message: string } {
  if (typeof window === 'undefined' || !window.localStorage) {
    return { success: false, message: 'LocalStorage unavailable' };
  }

  const snapshotKey = job.rollbackSnapshotKey || `saimetric_pre_migration_backup_${job.id}`;
  const backupData = window.localStorage.getItem(snapshotKey);

  if (!backupData) {
    return { success: false, message: 'No pre-migration snapshot found for this job.' };
  }

  try {
    if (job.entityType === 'inventory') {
      window.localStorage.setItem('saimetric_room_inventory_items', backupData);
    } else if (job.entityType === 'customers') {
      window.localStorage.setItem('saimetric_room_customers', backupData);
    } else if (job.entityType === 'suppliers') {
      window.localStorage.setItem('saimetric_room_suppliers', backupData);
    }

    job.status = 'ready';
    job.committedAt = undefined;
    saveMigrationJob(job);

    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('saimetric_inventory_updated', { detail: {} }));
      window.dispatchEvent(new CustomEvent('saimetric_customers_updated', { detail: {} }));
      window.dispatchEvent(new CustomEvent('saimetric_suppliers_updated', { detail: {} }));
    }

    return {
      success: true,
      message: `Successfully rolled back ${job.entityType} to its pre-migration snapshot.`,
    };
  } catch (err: any) {
    return {
      success: false,
      message: `Rollback failed: ${err.message}`,
    };
  }
}
