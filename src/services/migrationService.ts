export function getAllMigrationJobs(): MigrationJob[] {
  if (typeof window === 'undefined' || !window.localStorage) return [];
  try {
    const raw = window.localStorage.getItem(STORAGE_MIGRATION_JOBS_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (err) {
    console.error('[MigrationService] Error loading migration jobs:', err);
    return [];
  }
}

export function saveMigrationJob(job: MigrationJob): void {
  if (typeof window === 'undefined' || !window.localStorage) return;
  // Prune stagedRows for committed jobs to protect localStorage 5MB quota
  const jobs = getAllMigrationJobs().filter((j) => j.id !== job.id).map((j) => {
    if (j.status === 'committed' && j.stagedRows && j.stagedRows.length > 50) {
      return { ...j, stagedRows: [] };
    }
    return j;
  });
  jobs.unshift(job);
  try {
    window.localStorage.setItem(STORAGE_MIGRATION_JOBS_KEY, JSON.stringify(jobs));
  } catch (err: any) {
    console.warn('[MigrationService] Warning saving migration job to localStorage, trimming older jobs:', err);
    try {
      // Clear older safety backup keys if quota exceeded
      for (let i = window.localStorage.length - 1; i >= 0; i--) {
        const k = window.localStorage.key(i);
        if (k && k.startsWith('saimetric_pre_migration_backup_')) {
          window.localStorage.removeItem(k);
        }
      }
      const trimmedJobs = [job];
      window.localStorage.setItem(STORAGE_MIGRATION_JOBS_KEY, JSON.stringify(trimmedJobs));
    } catch (e2) {
      console.error('[MigrationService] Failed to save migration job even after trimming:', e2);
    }
  }
}

export function getMigrationJobById(id: string): MigrationJob | null {
  const jobs = getAllMigrationJobs();
  return jobs.find((j) => j.id === id) || null;
}

export function deleteMigrationJob(id: string): void {
  if (typeof window === 'undefined' || !window.localStorage) return;
  const jobs = getAllMigrationJobs().filter((j) => j.id !== id);
  window.localStorage.setItem(STORAGE_MIGRATION_JOBS_KEY, JSON.stringify(jobs));
}

