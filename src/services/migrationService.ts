export interface ParsedFileResult {
  headers: string[];
  rows: Record<string, any>[];
  totalCount: number;
}

/**
 * Parse any uploaded file (Excel .xlsx, .xls, CSV, TSV, or JSON)
 */
export async function parseLegacyFile(file: File): Promise<ParsedFileResult> {
  const fileName = file.name.toLowerCase();

  if (fileName.endsWith('.json')) {
    const text = await file.text();
    const parsed = JSON.parse(text);
    const dataRows = Array.isArray(parsed) ? parsed : parsed.items || parsed.data || [];
    if (!dataRows.length) {
      throw new Error('JSON file contains no data rows.');
    }
    const headers = Object.keys(dataRows[0]);
    return {
      headers,
      rows: dataRows,
      totalCount: dataRows.length,
    };
  }

  // Handle Excel and CSV via XLSX parser
  const buffer = await file.arrayBuffer();
  const workbook = XLSX.read(buffer, { type: 'array' });
  const firstSheetName = workbook.SheetNames[0];
  if (!firstSheetName) {
    throw new Error('Uploaded spreadsheet has no worksheets.');
  }

  const sheet = workbook.Sheets[firstSheetName];
  // Parse as raw 2D array of rows
  const rawData: any[][] = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: '' });
  if (rawData.length < 2) {
    throw new Error('Spreadsheet must contain at least a header row and 1 data row.');
  }

  // Extract headers
  const headerRow = rawData[0];
  const headers = headerRow.map((h: any, idx: number) => {
    const str = String(h ?? '').trim();
    return str || `Column_${idx + 1}`;
  });

  // Extract rows
  const rows: Record<string, any>[] = [];
  for (let r = 1; r < rawData.length; r++) {
    const rowValues = rawData[r];
    // Check if entire row is empty
    const hasData = rowValues.some((v: any) => v !== '' && v !== null && v !== undefined);
    if (!hasData) continue;

    const rowObj: Record<string, any> = {};
    headers.forEach((h: string, idx: number) => {
      rowObj[h] = rowValues[idx] !== undefined ? rowValues[idx] : '';
    });
    rows.push(rowObj);
  }

  return {
    headers,
    rows,
    totalCount: rows.length,
  };
}

/**
 * Parse pasted table text (from Excel clipboard or TSV)
 */
export function parsePastedTableText(text: string): ParsedFileResult {
  const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
  if (lines.length < 2) {
    throw new Error('Pasted text must contain at least a header line and 1 data line.');
  }

  // Detect delimiter: tab or comma
  const firstLine = lines[0];
  const delimiter = firstLine.includes('\t') ? '\t' : ',';

  const headers = firstLine.split(delimiter).map((h, idx) => h.trim().replace(/^"|"$/g, '') || `Column_${idx + 1}`);

  const rows: Record<string, any>[] = [];
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split(delimiter).map((v) => v.trim().replace(/^"|"$/g, ''));
    if (parts.length === 0 || parts.every((p) => p === '')) continue;

    const rowObj: Record<string, any> = {};
    headers.forEach((h, idx) => {
      rowObj[h] = parts[idx] !== undefined ? parts[idx] : '';
    });
    rows.push(rowObj);
  }

  return {
    headers,
    rows,
    totalCount: rows.length,
  };
}

